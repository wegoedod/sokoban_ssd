package sokoban.core;

/**
 * 정적 셀 종류. 3차원 격자의 모든 셀은 공중이다(바닥·중력 없음).
 * 블록·플레이어는 셀 종류가 아니라 {@link GameState}가 가진다.
 */
public enum TileType {
    /** 빈 공간. 플레이어도 블록도 지나다닌다. */
    EMPTY,
    /** 벽(고체). 플레이어도 블록도 들어갈 수 없다. */
    WALL,
    /**
     * 구멍. 블록이 들어오면 블록은 소멸하고 평범한 빈 칸이 된다. 플레이어는 진입 불가.
     * 레벨 파일의 {@code =}(메워진 구멍)는 이 타입이지만 {@link GameState}의 남은 구멍 집합에 들어 있지 않아
     * 처음부터 평범한 빈 칸처럼 동작한다.
     */
    HOLE,
    /** 목표 지점. 빈 칸처럼 지나다닌다. */
    GOAL,
    /**
     * 빙판. 블록이 진입하면 진행 방향으로 미끄러진다(레벨 디자인 M-05, 3D에서는 6방향 모두).
     * 플레이어는 평범한 칸처럼 걷는다.
     * TODO: 미끄러짐 처리는 엔진 PR에서 구현한다. 지금은 빈 칸과 똑같이 동작한다.
     */
    ICE,
    /**
     * 포탈. 짝이 되는 칸은 {@link Level#portalPartner(int)}로 찾는다(레벨 디자인 M-04).
     * 플레이어나 상자가 들어가면 짝 포탈 칸으로 전송된다. 짝 칸이 막혀 있으면 들어갈 수 없다(규칙은 {@link Engine}).
     */
    PORTAL
}
